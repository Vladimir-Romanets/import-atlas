'use strict';

// Bundles the viewer sources (src/render/*) into string constants that
// report/render.*.ts embeds into the generated single-file HTML. A build step, so the
// sources stay plain .css/.html files and real TypeScript ES modules rather
// than TS template literals.
//
// The client script is type-stripped, bundled and minified into one IIFE:
// the generated HTML is opened directly (file://) and can't load real
// <script type="module"> files from disk. esbuild only strips types —
// `npm run typecheck` (tsconfig.browser.json) is what checks them. Re-run
// via `npm run build` / `dev` / `typecheck` whenever src/render/* changes.

const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const RENDER_DIR = path.join(__dirname, '..', 'src', 'render');
const OUT_FILE = path.join(__dirname, '..', 'src', 'report', 'render.generated.ts');
const HELP_DIR = path.join(RENDER_DIR, 'client', 'help');
const HELP_OUT_FILE = path.join(RENDER_DIR, 'client', 'helpContent.generated.ts');

function readAsset(name) {
  return fs.readFileSync(path.join(RENDER_DIR, name), 'utf8');
}

// Escapes `source` so it survives being wrapped in backticks in the
// generated .ts files. Backslashes go first: escaping them last would double
// up the ones the other two steps introduced. A lone `$` is left alone —
// only `${` opens an interpolation.
function toTemplateLiteral(source) {
  return source.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

// One skeleton (render.html) serves both viewers: sidebar, tabs, canvas and
// Findings panel are the same markup, and the few spots that aren't are filled
// from VARIANTS below. `{{name}}` is safe to write in the .html sources —
// nothing in it collides with the template-literal escaping above, which runs
// after this.
//
// A placeholder alone on its line takes that line's indentation with it: an
// empty value leaves no blank line behind, and a multi-line one stays aligned.
function renderTemplate(source, vars) {
  const lookup = (name) => {
    if (!Object.prototype.hasOwnProperty.call(vars, name)) {
      throw new Error(`render.html references an unknown placeholder: {{${name}}}`);
    }
    return vars[name];
  };

  return source
    .replace(/^([ \t]*)\{\{(\w+)\}\}[ \t]*\n/gm, (_match, indent, name) => {
      const value = lookup(name);
      if (value === '') return '';
      return `${value
        .split('\n')
        .map((line) => (line === '' ? line : indent + line))
        .join('\n')}\n`;
    })
    .replace(/\{\{(\w+)\}\}/g, (_match, name) => lookup(name));
}

// The tree viewer draws no back edges — a tree can't close a cycle — so it is
// the one legend entry the shared skeleton can't state unconditionally.
const VARIANTS = {
  tree: {
    tabLabel: 'Tree',
    canvasLabel: 'Import dependency tree',
    edgeLegendExtra: '',
    hintFile: 'render.tree.hint.html'
  },
  graph: {
    tabLabel: 'Graph',
    canvasLabel: 'Import dependency graph',
    edgeLegendExtra: '<li><span class="edge-sample back"></span>closes a cycle</li>',
    hintFile: 'render.graph.hint.html'
  }
};

function buildBody(variant) {
  const { hintFile, ...vars } = VARIANTS[variant];
  return renderTemplate(readAsset('render.html'), {
    ...vars,
    hint: readAsset(hintFile).trimEnd()
  });
}

// Findings groups reference a help fragment by slug, which is their group
// key ("dead-export-low"). A slug with no matching file gets no help icon.
function writeHelpContent() {
  const entries = fs.existsSync(HELP_DIR)
    ? fs
        .readdirSync(HELP_DIR)
        .filter((name) => name.endsWith('.html'))
        .map((name) => {
          const slug = name.slice(0, -'.html'.length);
          const html = toTemplateLiteral(fs.readFileSync(path.join(HELP_DIR, name), 'utf8').trim());
          return `  '${slug}': \`${html}\`,`;
        })
    : [];

  const output = `// Auto-generated by scripts/generate-render-assets.js — do not edit by hand.
// Edit the .html fragments in src/render/client/help/ instead, then re-run \`npm run build\`
// (or \`npm run dev\`). Bundled into the client script by esbuild like any other client module.

export const HELP_HTML: Record<string, string> = {
${entries.join('\n')}
};
`;

  fs.writeFileSync(HELP_OUT_FILE, output);
}

// Each viewer is bundled separately rather than into one script branching at
// runtime: a report renders only one of them, and a self-contained HTML file
// should not carry the other viewer's code around inside it.
async function bundleClient(entry) {
  const bundle = await esbuild.build({
    entryPoints: [path.join(RENDER_DIR, entry)],
    bundle: true,
    minify: true,
    format: 'iife',
    platform: 'browser',
    write: false
  });
  return bundle.outputFiles[0].text;
}

async function main() {
  // Before the esbuild bundles below, so the client scripts can import from
  // it like a normal module.
  writeHelpContent();

  const treeScript = toTemplateLiteral(await bundleClient('render.tree.client.ts'));
  const graphScript = toTemplateLiteral(await bundleClient('render.graph.client.ts'));

  const treeCss = toTemplateLiteral(readAsset('render.base.css'));
  const treeHtml = toTemplateLiteral(buildBody('tree'));
  // The graph viewer's stylesheet extends the shared base rather than
  // restating it, so it is emitted appended.
  const graphCss = toTemplateLiteral(
    `${readAsset('render.base.css')}\n${readAsset('render.graph.css')}`
  );
  const graphHtml = toTemplateLiteral(buildBody('graph'));

  const output = `// Auto-generated by scripts/generate-render-assets.js — do not edit by hand.
// Edit the sources in src/render/ instead, then re-run \`npm run build\` (or \`npm run dev\`).

export const CSS_TREE = \`${treeCss}\`;

export const BODY_TREE = \`${treeHtml}\`;

export const SCRIPT_TREE = \`${treeScript}\`;

export const CSS_GRAPH = \`${graphCss}\`;

export const BODY_GRAPH = \`${graphHtml}\`;

export const SCRIPT_GRAPH = \`${graphScript}\`;
`;

  fs.writeFileSync(OUT_FILE, output);
}

// Guarded so the unit test can require this file for `toTemplateLiteral`
// without kicking off a full esbuild run.
if (require.main === module) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}

module.exports = { toTemplateLiteral, renderTemplate, buildBody, VARIANTS };
